// Codigos de paises comunes (Set para busqueda rapida)
const commonCodes = new Set(commonCountries.map(c => c.code))

/**
 * Lista combinada: primero comunes, luego resto alfabetico
 * Sin duplicados
 */
export const countriesGrouped = [
  { group: 'Mas comunes', countries: commonCountries },
  { group: 'Todos los paises', countries: allCountries.filter(c => !commonCodes.has(c.code)) }
]

/**
 * Buscar pais por codigo ISO
 */
export function getCountryByCode(code) {
  return allCountries.find(c => c.code === code) || commonCountries.find(c => c.code === code)
}

/**
 * Filtrar paises por texto (busqueda)
 */
export function searchCountries(query) {
  if (!query) return allCountries
  const q = query.toLowerCase()
  return allCountries.filter(c =>
    c.label.toLowerCase().includes(q) || c.code.toLowerCase().includes(q)
  )
}

export default allCountries
